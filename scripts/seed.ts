async function seed() {
  console.log('🌱 Starting database seeding...');
  await connectDB();

  // Clear existing sample jobs with sample hashes
  await Job.deleteMany({ sourceHash: { $regex: /^sample-hash/ } });

  // Seed Categories
  await Category.deleteMany({});
  for (const cat of CATEGORIES) {
    await Category.create({
      name: cat.name,
      slug: cat.slug,
      icon: cat.icon,
      description: cat.description,
      displayOrder: cat.displayOrder,
      jobCount: 0,
    });
  }
  console.log(`✅ Seeded ${CATEGORIES.length} categories.`);

  // Insert jobs
  for (const job of SAMPLE_JOBS) {
    await Job.create(job);
  }
  console.log(`✅ Seeded ${SAMPLE_JOBS.length} realistic Sarkari job postings.`);

  // Update category counts
  for (const cat of CATEGORIES) {
    const count = await Job.countDocuments({ category: cat.name, isActive: true });
    await Category.updateOne({ slug: cat.slug }, { $set: { jobCount: count } });
  }
  console.log('✅ Updated category counts.');

  console.log('🎉 Seeding completed successfully!');
  process.exit(0);
}

seed().catch((err) => {
  console.error('❌ Seeding failed:', err);
  process.exit(1);
});
